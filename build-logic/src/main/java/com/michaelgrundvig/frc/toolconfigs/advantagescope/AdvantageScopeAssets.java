package com.michaelgrundvig.frc.toolconfigs.advantagescope;

import com.michaelgrundvig.frc.world.tools.AdvantageScopeRelease;
import com.michaelgrundvig.frc.world.tools.RobotCatalog;
import com.michaelgrundvig.frc.world.tools.RobotDescription;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;

/**
 * A robot for AdvantageScope's 3D field, generated from its configuration: a schematic model and
 * the {@code config.json} that places it, in the custom-assets format of AdvantageScope {@value
 * AdvantageScopeRelease#VERSION} (its documentation's "Custom Assets" page, and {@code parseRobot}
 * in its {@code src/main/assetUtil.ts}, read at that release). The build writes them into {@code
 * ascope_assets/}, committed, for AdvantageScope's <i>Use Custom Assets Folder</i>; nothing on the
 * robot reads them.
 *
 * <p><b>What it draws</b> ({@link #DRAWN}), in flat colors:
 *
 * <ul>
 *   <li>the frame, a see-through box at the frame's length and width, from the bumpers' bottom to
 *       the robot's overall height, so what's inside it shows;
 *   <li>the bumpers, a ring as thick as they are, from their bottom to their top;
 *   <li>an arrow on the frame's top pointing forward;
 *   <li>each camera, a small box at its lens with an arrow along its optical axis, and its field of
 *       view, a see-through pyramid out to its sight range, as wide as its lens calibration sees
 *       where it has one;
 *   <li>the gyro's IMU, a small block where its mount puts it, when the robot gives one;
 *   <li>each wheel, a disc at its module with an arrow the way it rolls forward. The wheels are
 *       AdvantageScope's "components" 0 to 3, which the robot turns by its logged module poses
 *       ({@code Drive/ModulePoses}); without them they stand pointing forward.
 * </ul>
 *
 * <p><b>What it drops</b> ({@link #DROPPED}; a test pins the list): everything that isn't drawn.
 * The mass, its inertia and the center of gravity; the drivetrain's motors, gearing, coupling, grip
 * and inertias; each camera's noise, frame rate, latency and mount tolerance; a camera that rides a
 * mechanism, whose cone would need posing with its joint. The mechanisms themselves aren't drawn
 * yet. How the drivetrain is driven (its limits and gains), the robot's vision and estimator
 * settings, its wiring, the backup IMU, and the gyro's orientation and accelerometer check never
 * reach it.
 *
 * <p><b>Two models a robot.</b> {@code Robot_<name>/} is the robot with its cameras' fields of
 * view; {@code Robot_<name>_NoCones/} is the same without them, for a second copy drawn beside it
 * (the simulator's truth, as a ghost), whose cones would only crowd the view. The fields of view
 * are a component of their own (after the wheels), not part of the base model: AdvantageScope sizes
 * its swerve overlay from the base model's extent, which a 7 m cone would throw off. A component
 * with no logged pose stays where it was drawn.
 *
 * <p><b>Coordinates.</b> The robot's frame is the configuration's: x forward, y left, z up, from
 * the frame's center on the floor, which is where AdvantageScope puts the logged pose. The glTF
 * files use glTF's own axes ({@link Glb}), and every config turns them back with {@link
 * RobotConfigJson#GLTF_TO_ROBOT}. Each wheel is drawn where it sits, and its component's zeroed
 * position moves it back to the origin, so a logged pose at the wheel's center, turned to its
 * angle, puts it there.
 *
 * <p>Every file comes out the same, byte for byte, for the same configuration on any computer: the
 * build compares them with what's committed.
 */
public final class AdvantageScopeAssets {
  /** What each glTF file says made it, and that it's generated. */
  static final String GENERATOR =
      "AdvantageScopeAssets, from the robot's configuration (Robots.java): generated by the"
          + " build, do not edit";

  /** The configuration values the model draws. */
  public static final List<String> DRAWN =
      List.of(
          "Body.frameLength",
          "Body.frameWidth",
          "Body.overallHeight",
          "Body.bumperThickness",
          "Body.bumperThicknessLeftRight",
          "Body.bumperBottom",
          "Body.bumperTop",
          "Drivetrain.corners",
          "Drivetrain.Corner.module",
          "Drivetrain.Corner.position",
          "Drivetrain.Module.wheelRadius",
          "CameraConfig.name",
          "CameraConfig.forward",
          "CameraConfig.left",
          "CameraConfig.up",
          "CameraConfig.roll",
          "CameraConfig.tiltUp",
          "CameraConfig.yaw",
          "CameraConfig.sensor",
          "CameraConfig.software",
          "CameraConfig.ImageSensor.widthPixels",
          "CameraConfig.ImageSensor.heightPixels",
          "CameraConfig.ImageSensor.fieldOfView",
          "CameraConfig.ImageSensor.fieldOfViewAcross",
          "CameraConfig.ImageSensor.sightRange");

  /** The configuration values the model leaves out: AdvantageScope has no place for them. */
  public static final List<String> DROPPED =
      List.of(
          "Body.weight",
          "Body.cg",
          "Body.inertia",
          "Drivetrain.Module.driveMotor",
          "Drivetrain.Module.steerMotor",
          "Drivetrain.Module.driveGearing",
          "Drivetrain.Module.steerGearing",
          "Drivetrain.Module.wheelCoefficientOfFriction",
          "Drivetrain.Module.driveInertia",
          "Drivetrain.Module.steerInertia",
          "Drivetrain.Module.couplingRatio",
          "Drivetrain.wiring",
          "Drivetrain.control",
          "CameraConfig.noiseScale",
          "CameraConfig.joint",
          "CameraConfig.mountTolerance",
          "CameraConfig.ImageSensor.frameRate",
          "CameraConfig.ImageSensor.latency");

  /** The wheels, in the drivetrain's order, as the module poses are logged. */
  static final List<String> WHEELS =
      List.of("front left", "front right", "back left", "back right");

  private static final String GENERATED_NOTE =
      """
      # Generated: don't edit

      The build writes this folder from the robot's configuration in `Robots.java`
      (`./gradlew advantageScopeAssets`, part of every build), for AdvantageScope's
      *Use Custom Assets Folder*. The next build writes over any edit here: change the
      robot in `Robots.java` instead. See docs/simulator.md, "See it in AdvantageScope".
      """;

  private AdvantageScopeAssets() {}

  /**
   * Writes the robots' folders: {@code --catalog=<class> --out=<folder> [--robot=<name>]...}. With
   * no robot named, every robot the catalog has. The build's AdvantageScope plugin runs this on the
   * compiled program; it only builds the robots' configuration records and writes files.
   *
   * @throws IllegalArgumentException for a missing or unknown argument, or a robot the catalog
   *     doesn't have
   */
  public static void main(String... args) throws IOException, ReflectiveOperationException {
    AssetArguments arguments = AssetArguments.parse(args);
    RobotCatalog catalog =
        Class.forName(arguments.catalogClass())
            .asSubclass(RobotCatalog.class)
            .getDeclaredConstructor()
            .newInstance();
    write(robotsToWrite(catalog, arguments.robots()), arguments.out());
  }

  /** The robots named, or every robot the catalog has when none is named. */
  private static List<RobotDescription> robotsToWrite(RobotCatalog catalog, List<String> names) {
    if (names.isEmpty()) {
      return catalog.all();
    }
    return names.stream().map(catalog::named).toList();
  }

  /**
   * Writes each robot's two folders into a folder.
   *
   * @throws IllegalArgumentException if two robots' folders would have the same name
   */
  public static void write(List<RobotDescription> robots, Path folder) throws IOException {
    // Nothing is written until every robot is known to have a folder of its own.
    Map<String, String> robotByFolder = new HashMap<>();
    for (RobotDescription robot : robots) {
      String earlier = robotByFolder.put(folder(robot.name()), robot.name());
      if (earlier != null) {
        throw new IllegalArgumentException(
            "the robots " + earlier + " and " + robot.name() + " would share a folder");
      }
    }
    for (RobotDescription robot : robots) {
      for (Map.Entry<String, byte[]> file : files(robot).entrySet()) {
        Path path = folder.resolve(file.getKey());
        Files.createDirectories(path.getParent());
        Files.write(path, file.getValue());
      }
    }
  }

  /**
   * The folder AdvantageScope reads a robot from: {@code Robot_} and its name, kept to letters,
   * digits, dashes and underscores.
   */
  public static String folder(String robot) {
    return "Robot_" + robot.replaceAll("[^A-Za-z0-9_-]", "_");
  }

  /** The folder of the robot without its fields of view. */
  public static String withoutConesFolder(String robot) {
    return folder(robot) + "_NoCones";
  }

  /** The model's name, as AdvantageScope lists it to choose for a robot. */
  public static String modelName(String robot) {
    return robot + " (schematic)";
  }

  /** The name of the model without the fields of view. */
  public static String withoutConesModelName(String robot) {
    return robot + " (schematic, no cones)";
  }

  /**
   * Every file of a robot's two folders, by its path from the assets folder.
   *
   * <p>AdvantageScope reads a folder's {@code model.glb} as the robot's base model, and {@code
   * model_0.glb}, {@code model_1.glb} and on as its components, in the order its config lists them:
   * here each wheel, and then the fields of view. The two folders hold the same base model and
   * wheels; only the one with cones has the fields of view, and only if the robot has a camera to
   * draw one for.
   */
  public static Map<String, byte[]> files(RobotDescription robot) {
    byte[] baseModel = Glb.write(GENERATOR, RobotSchematic.body(robot));
    List<byte[]> wheelModels = new ArrayList<>();
    for (RobotSchematic.WheelModel wheel : RobotSchematic.wheels(robot)) {
      wheelModels.add(Glb.write(GENERATOR, wheel.meshes()));
    }
    List<Mesh> cones = RobotSchematic.cones(robot);
    byte[] note = GENERATED_NOTE.getBytes(StandardCharsets.UTF_8);

    Map<String, byte[]> files = new TreeMap<>();
    for (SchematicModel model : SchematicModel.values()) {
      String folder = model.folder(robot.name());
      boolean conesAreDrawn = model == SchematicModel.WITH_CONES && !cones.isEmpty();
      files.put(folder + "/config.json", RobotConfigJson.write(robot, model, conesAreDrawn));
      files.put(folder + "/model.glb", baseModel);
      for (int wheel = 0; wheel < wheelModels.size(); wheel++) {
        files.put(folder + "/model_" + wheel + ".glb", wheelModels.get(wheel));
      }
      if (conesAreDrawn) {
        int afterTheWheels = wheelModels.size();
        files.put(folder + "/model_" + afterTheWheels + ".glb", Glb.write(GENERATOR, cones));
      }
      files.put(folder + "/GENERATED.md", note);
    }
    return files;
  }
}
